'use client'

import React from 'react'
import { motion, AnimatePresence } from 'framer-motion'
import { ParsedResume, AtsScoreBreakdown, AIFeedbackReport, FormattingAnalysisResult } from '@/lib/resume/types'
import { generateRewrittenResume } from '@/lib/resume/rewriter'
import { Button } from '@/components/ui/button'
import { Download, X, FileText, CheckCircle2, Award, Sparkles, Code2 } from 'lucide-react'

interface ExportReportModalProps {
  isOpen: boolean
  onClose: () => void
  resume: ParsedResume
  atsBreakdown: AtsScoreBreakdown
  aiFeedback: AIFeedbackReport
  formatting: FormattingAnalysisResult
}

export function ExportReportModal({
  isOpen,
  onClose,
  resume,
  atsBreakdown,
  aiFeedback,
  formatting
}: ExportReportModalProps) {
  if (!isOpen) return null

  const candidateName = resume.contact.name || 'Candidate'
  const filePrefix = candidateName.replace(/\s+/g, '_')

  // Download Trigger Helper
  const downloadFile = (content: string, filename: string, mime: string) => {
    const blob = new Blob([content], { type: mime })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = filename
    document.body.appendChild(a)
    a.click()
    document.body.removeChild(a)
    URL.revokeObjectURL(url)
  }

  // 1. Download Improved Resume (.md)
  const handleDownloadResume = () => {
    const rewritten = generateRewrittenResume(resume)
    downloadFile(rewritten.fullResumeMarkdown, `${filePrefix}_Optimized_Resume.md`, 'text/markdown;charset=utf-8')
  }

  // 2. Download Complete Analysis Report (.txt)
  const handleDownloadAnalysisReport = () => {
    const reportText = `=====================================================
AI RESUME ANALYZER — COMPREHENSIVE AUDIT REPORT
=====================================================
Candidate Name : ${candidateName}
Overall Score  : ${atsBreakdown.overallScore} / 100 (Grade: ${atsBreakdown.overallGrade})
Evaluated At   : ${new Date().toLocaleString()}

SUMMARY EVALUATION:
-------------------
${atsBreakdown.overallSummary}

CATEGORY-WISE ATS SCORES:
-------------------------
${Object.values(atsBreakdown.categories)
  .map(c => `• ${c.name.padEnd(25)}: ${c.score}/${c.maxScore} pts (${c.percentage}%) - ${c.feedback}`)
  .join('\n')}

FORMATTING & METRICS:
---------------------
• Word Count       : ${formatting.wordCount} words (~${formatting.estimatedPages} pages)
• Bullet Points    : ${formatting.bulletPointCount}
• Reading Ease     : ${formatting.fleschReadingEase}/100 (${formatting.readabilityGrade})
• Paragraph Health : ${formatting.paragraphDensityWarning ? 'Contains dense blocks (>65 words)' : 'Optimal'}

AI RECRUITER PERSPECTIVE:
-------------------------
${aiFeedback.recruiterPerspective}

KEY RECOMMENDATIONS:
--------------------
${aiFeedback.readabilityImprovements.map(r => `• ${r}`).join('\n')}

=====================================================
Generated by AI Resume Analyzer (AETHERCV AI)
=====================================================
`
    downloadFile(reportText, `${filePrefix}_Analysis_Report.txt`, 'text/plain;charset=utf-8')
  }

  // 3. Download Feedback Report (.txt)
  const handleDownloadFeedbackReport = () => {
    const feedbackText = `=====================================================
AI RESUME FEEDBACK & CAREER ADVICE REPORT
=====================================================
Candidate Name : ${candidateName}

PROFESSIONAL REVIEW:
${aiFeedback.professionalReview}

RECOMMENDED SENTENCE REWRITES:
${aiFeedback.sentenceRewrites
  .map((s, idx) => `
${idx + 1}. [Original] : "${s.original}"
   [Rewritten]: "${s.improved}"
   [Rationale]: ${s.explanation}`)
  .join('\n')}

CAREER ADVICE:
${aiFeedback.careerAdvice.map(a => `• ${a}`).join('\n')}

SKILL SUGGESTIONS:
${aiFeedback.skillsSuggestions.map(s => `• ${s}`).join('\n')}
`
    downloadFile(feedbackText, `${filePrefix}_Feedback_Report.txt`, 'text/plain;charset=utf-8')
  }

  // 4. Download Full ATS JSON Audit
  const handleDownloadJson = () => {
    const exportData = {
      candidateName,
      evaluatedAt: new Date().toISOString(),
      atsScore: atsBreakdown.overallScore,
      atsBreakdown,
      parsedData: resume,
      aiFeedback,
      formatting
    }
    downloadFile(JSON.stringify(exportData, null, 2), `${filePrefix}_ATS_Audit.json`, 'application/json;charset=utf-8')
  }

  const exportOptions = [
    {
      title: 'Optimized Resume (.md)',
      description: 'Clean executive Markdown with enhanced bullet points, active verbs, and quantified outcomes.',
      icon: Sparkles,
      color: 'text-sky-300 bg-sky-500/10 border-sky-500/30',
      action: handleDownloadResume,
      btnLabel: 'Download Resume'
    },
    {
      title: 'Comprehensive Analysis Report (.txt)',
      description: '10-category scoring audit, formatting benchmarks, and recruiter scan simulation notes.',
      icon: Award,
      color: 'text-blue-300 bg-blue-500/10 border-blue-500/30',
      action: handleDownloadAnalysisReport,
      btnLabel: 'Download Audit'
    },
    {
      title: 'Actionable Feedback Report (.txt)',
      description: 'Sentence-by-sentence before/after rewrites, grammar notes, and targeted career advice.',
      icon: CheckCircle2,
      color: 'text-cyan-300 bg-cyan-500/10 border-cyan-500/30',
      action: handleDownloadFeedbackReport,
      btnLabel: 'Download Feedback'
    },
    {
      title: 'Full ATS Machine Data (.json)',
      description: 'Structured JSON containing parsed skills, contact links, experience items, and raw metrics.',
      icon: Code2,
      color: 'text-indigo-300 bg-indigo-500/10 border-indigo-500/30',
      action: handleDownloadJson,
      btnLabel: 'Export JSON'
    }
  ]

  return (
    <AnimatePresence>
      <div className="fixed inset-0 z-50 flex items-center justify-center p-4">
        {/* Backdrop */}
        <motion.div
          initial={{ opacity: 0 }}
          animate={{ opacity: 1 }}
          exit={{ opacity: 0 }}
          onClick={onClose}
          className="fixed inset-0 bg-[#08111F]/80 backdrop-blur-md"
        />

        {/* Modal Dialog */}
        <motion.div
          initial={{ opacity: 0, scale: 0.95, y: 15 }}
          animate={{ opacity: 1, scale: 1, y: 0 }}
          exit={{ opacity: 0, scale: 0.95, y: 15 }}
          transition={{ duration: 0.2 }}
          className="relative w-full max-w-xl bg-[#0F172A] border border-blue-500/25 shadow-[0_0_50px_rgba(37,99,235,0.25)] rounded-3xl p-6 sm:p-7 z-10 space-y-6"
        >
          <div className="flex items-center justify-between pb-3.5 border-b border-blue-500/20">
            <div className="flex items-center gap-3">
              <div className="p-2.5 rounded-2xl bg-blue-500/15 border border-blue-500/30 text-sky-400 shadow-[0_0_15px_rgba(59,130,246,0.25)]">
                <Download className="w-5 h-5" />
              </div>
              <div>
                <h3 className="text-lg font-bold font-poppins text-white">Export Resume &amp; Audit Reports</h3>
                <p className="text-xs text-slate-400 font-outfit">Select the desired report format</p>
              </div>
            </div>
            <button
              type="button"
              onClick={onClose}
              aria-label="Close modal"
              className="p-2 rounded-xl text-slate-400 hover:text-white hover:bg-blue-600/20 transition-colors"
            >
              <X className="w-5 h-5" />
            </button>
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3.5">
            {exportOptions.map((opt, idx) => {
              const Icon = opt.icon
              return (
                <div
                  key={idx}
                  className="p-4 sm:p-5 rounded-2xl bg-[#08111F]/90 border border-blue-500/20 flex flex-col justify-between space-y-3.5 hover:border-sky-400/40 transition-all shadow-[0_4px_15px_rgba(0,0,0,0.2)]"
                >
                  <div className="space-y-2">
                    <div className="flex items-center gap-2">
                      <div className={`p-1.5 rounded-lg border ${opt.color}`}>
                        <Icon className="w-4 h-4" />
                      </div>
                      <h4 className="text-xs font-bold font-poppins text-white">{opt.title}</h4>
                    </div>
                    <p className="text-[11px] text-slate-400 font-outfit leading-relaxed">
                      {opt.description}
                    </p>
                  </div>
                  <Button
                    size="sm"
                    onClick={opt.action}
                    className="w-full text-xs font-outfit gap-1.5 bg-gradient-to-r from-[#4D48E6] via-[#2662EB] to-[#1E50DA] hover:opacity-95 text-white shadow-[0_0_15px_rgba(77,72,230,0.35)] transition-all"
                  >
                    <Download className="w-3.5 h-3.5" />
                    {opt.btnLabel}
                  </Button>
                </div>
              )
            })}
          </div>

          <div className="pt-2 border-t border-blue-500/20 text-center">
            <p className="text-[11px] text-slate-400 font-outfit">
              All files are processed and generated entirely within your browser for complete data privacy.
            </p>
          </div>
        </motion.div>
      </div>
    </AnimatePresence>
  )
}
